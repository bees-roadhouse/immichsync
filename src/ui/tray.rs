const ID_PAUSE: &str = "pause";
const ID_RESUME: &str = "resume";
const ID_UPLOAD_NOW: &str = "upload_now";
const ID_SETTINGS: &str = "settings";
const ID_ABOUT: &str = "about";
const ID_VIEW_LOG: &str = "view_log";
const ID_VIEW_TRASH: &str = "view_trash";
const ID_CHECK_UPDATES: &str = "check_updates";
const ID_UPDATE_AVAILABLE: &str = "update_available";
const ID_RESTART_TO_UPDATE: &str = "restart_to_update";
const ID_QUIT: &str = "quit";

// ---------------------------------------------------------------------------
// Brand icon pixel data (generated by build.rs from assets/icon-source.webp)
// ---------------------------------------------------------------------------

/// Tray icon dimension (square). Must match build.rs::TRAY_SIZE.
pub const TRAY_ICON_SIZE: u32 = 32;
const TRAY_ICON_BYTES: usize = (TRAY_ICON_SIZE as usize) * (TRAY_ICON_SIZE as usize) * 4;

/// Number of frames in the syncing animation. Must match build.rs::ROT_FRAMES.
pub const ROT_FRAME_COUNT: usize = 12;

/// One full rotation per `ROT_PERIOD`. 100ms per frame x 12 frames = 1.2s.
pub const ROT_FRAME_INTERVAL: Duration = Duration::from_millis(100);

const IDLE_RGBA: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/icons/tray_idle.rgba"));
const OFFLINE_RGBA: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/icons/tray_offline.rgba"));

/// All rotation frames. Each is a 32x32 RGBA8 raw bitmap.
///
/// Frame 0 is the canonical orientation (matches `IDLE_RGBA`). Frames 1..11
/// are rotated clockwise in 30 degree increments.
const ROT_FRAMES: [&[u8]; ROT_FRAME_COUNT] = [
    include_bytes!(concat!(env!("OUT_DIR"), "/icons/tray_rot_00.rgba")),
    include_bytes!(concat!(env!("OUT_DIR"), "/icons/tray_rot_01.rgba")),
    include_bytes!(concat!(env!("OUT_DIR"), "/icons/tray_rot_02.rgba")),
    include_bytes!(concat!(env!("OUT_DIR"), "/icons/tray_rot_03.rgba")),
    include_bytes!(concat!(env!("OUT_DIR"), "/icons/tray_rot_04.rgba")),
    include_bytes!(concat!(env!("OUT_DIR"), "/icons/tray_rot_05.rgba")),
    include_bytes!(concat!(env!("OUT_DIR"), "/icons/tray_rot_06.rgba")),
    include_bytes!(concat!(env!("OUT_DIR"), "/icons/tray_rot_07.rgba")),
    include_bytes!(concat!(env!("OUT_DIR"), "/icons/tray_rot_08.rgba")),
    include_bytes!(concat!(env!("OUT_DIR"), "/icons/tray_rot_09.rgba")),
    include_bytes!(concat!(env!("OUT_DIR"), "/icons/tray_rot_10.rgba")),
    include_bytes!(concat!(env!("OUT_DIR"), "/icons/tray_rot_11.rgba")),
];

// Compile-time sanity: build.rs must produce blobs that match the declared
// dimensions. If someone changes TRAY_SIZE in build.rs without touching here,
// the build fails immediately rather than producing a corrupted runtime icon.
const _: () = {
    assert!(IDLE_RGBA.len() == TRAY_ICON_BYTES);
    assert!(OFFLINE_RGBA.len() == TRAY_ICON_BYTES);
    // Can't iterate const arrays in stable const fn yet ... spot-check the
    // first frame; build.rs writes them with a fixed format so if one is
    // right the rest are too.
    assert!(ROT_FRAMES[0].len() == TRAY_ICON_BYTES);
};

/// Build a tray-icon `Icon` from a raw RGBA8 blob of `TRAY_ICON_SIZE` square.
fn icon_from_rgba(rgba: &[u8]) -> Result<Icon, TrayError> {
    // tray-icon takes ownership of the Vec, so we clone the static slice
    // into a fresh allocation each time. Cheap (4 KiB per swap) and lets
    // the static slices stay 'static.
    Icon::from_rgba(rgba.to_vec(), TRAY_ICON_SIZE, TRAY_ICON_SIZE)
        .map_err(|e| TrayError::IconCreate(e.to_string()))
}

/// The RGBA blob for the canonical (frame-0) brand icon. Used by window
/// dialogs that want the static brand mark.
pub fn brand_icon_rgba() -> &'static [u8] {
    IDLE_RGBA
}

/// The RGBA blob and dimensions for the eframe window icon helper in
/// `crate::ui::window_icon`. Exposed so `set_window_icon` can ship the
/// same bitmap that the tray uses.
pub fn brand_icon_dimensions() -> (u32, u32) {
    (TRAY_ICON_SIZE, TRAY_ICON_SIZE)
}

// ---------------------------------------------------------------------------
// Icon selection by logical state
// ---------------------------------------------------------------------------

/// Pick the static icon for a given state. Syncing is animated externally
/// via `tick_animation`, so its still-frame returned here is the current
/// frame index when first entering Syncing (frame 0).
fn static_icon_for_state(state: &TrayState) -> Result<Icon, TrayError> {
    match state {
        TrayState::Idle => icon_from_rgba(IDLE_RGBA),
        TrayState::Syncing { .. } => icon_from_rgba(ROT_FRAMES[0]),
        // Paused / Error / Offline all use the offline overlay variant.
        // Distinct error states differ in tooltip + status text, not in
        // the icon. (Out of scope: a separate "paused" badge variant.)
        TrayState::Paused => icon_from_rgba(OFFLINE_RGBA),
        TrayState::Error(_) => icon_from_rgba(OFFLINE_RGBA),
        TrayState::Offline => icon_from_rgba(OFFLINE_RGBA),
    }
}

fn tooltip_for_state(state: &TrayState) -> String {
    match state {
        TrayState::Idle => "ImmichSync ... Idle".to_owned(),
        TrayState::Syncing { current, total } => {
            format!("ImmichSync ... Uploading {}/{}", current, total)
        }
        TrayState::Paused => "ImmichSync ... Paused".to_owned(),
        TrayState::Error(msg) => format!("ImmichSync ... Error: {}", msg),
        TrayState::Offline => "ImmichSync ... Offline".to_owned(),
    }
}

fn status_text_for_state(state: &TrayState) -> String {
    match state {
        TrayState::Idle => "Idle ... watching for new files".to_owned(),
        TrayState::Syncing { current, total } => {
            format!("Uploading {}/{} files...", current, total)
        }
        TrayState::Paused => "Paused".to_owned(),
        TrayState::Error(msg) => format!("Error: {}", msg),
        TrayState::Offline => "Server offline".to_owned(),
    }
}

// ---------------------------------------------------------------------------
// State machine (next-state transitions + animation cursor)
// ---------------------------------------------------------------------------

/// Returns true if the given pair represents a Syncing -> not-Syncing
/// transition, where the tray icon must snap back to a stable static frame.
fn is_syncing_exit(prev: &TrayState, next: &TrayState) -> bool {
    matches!(prev, TrayState::Syncing { .. }) && !matches!(next, TrayState::Syncing { .. })
}


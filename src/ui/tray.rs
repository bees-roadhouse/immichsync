// System tray icon and context menu via the `tray-icon` crate (0.19).
//
// The tray icon must be created on the main thread after the winit event loop
// has been set up (or on Windows it can be created before the loop starts,
// but must be driven from the main thread).
//
// Brand icon pipeline (issue #38):
//   * build.rs renders all icon pixels from `assets/icon-source.webp` at
//     compile time and writes raw 32x32 RGBA8 blobs into OUT_DIR/icons/.
//   * `include_bytes!` brings them into the binary here ... zero runtime
//     image-decode cost and no `image` crate at runtime.
//   * Three logical states: Idle (static), Syncing (frame-cycle every
//     ~100ms), Offline (desaturated + corner slash badge).
//   * Frame cycling is driven externally from `app.rs::run`'s main loop
//     calling `tick_animation()` once per pass; the tray owns the
//     timer + frame index.

use std::sync::mpsc;
use std::time::{Duration, Instant};

use thiserror::Error;
use tray_icon::{
    menu::{Menu, MenuEvent, MenuItem, PredefinedMenuItem},
    Icon, TrayIcon, TrayIconAttributes,
};

// ---------------------------------------------------------------------------
// Public types
// ---------------------------------------------------------------------------

/// The logical state of the tray icon.
#[derive(Debug, Clone, PartialEq)]
pub enum TrayState {
    /// Connected and watching; nothing in queue.
    Idle,
    /// Actively uploading files.
    Syncing { current: u32, total: u32 },
    /// User has paused syncing.
    Paused,
    /// An error has occurred (server unreachable, auth failure, etc.).
    Error(String),
    /// No network / server not reachable.
    Offline,
}

/// User actions emitted by the tray menu.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum TrayAction {
    Pause,
    Resume,
    UploadNow,
    OpenSettings,
    About,
    ViewLog,
    ViewTrash,
    CheckForUpdates,
    OpenUpdateDialog,
    RestartToUpdate,
    Quit,
}

// ---------------------------------------------------------------------------
// Errors
// ---------------------------------------------------------------------------

#[derive(Debug, Error)]
pub enum TrayError {
    #[error("failed to create tray icon: {0}")]
    IconCreate(String),

    #[error("failed to build tray icon: {0}")]
    Build(String),
}


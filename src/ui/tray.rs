#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn frame_set_has_twelve_frames_of_correct_size() {
        assert_eq!(ROT_FRAMES.len(), ROT_FRAME_COUNT);
        for (i, frame) in ROT_FRAMES.iter().enumerate() {
            assert_eq!(
                frame.len(),
                TRAY_ICON_BYTES,
                "frame {} has wrong byte count",
                i
            );
        }
    }

    #[test]
    fn idle_and_offline_blobs_are_correct_size() {
        assert_eq!(IDLE_RGBA.len(), TRAY_ICON_BYTES);
        assert_eq!(OFFLINE_RGBA.len(), TRAY_ICON_BYTES);
    }

    #[test]
    fn frame_zero_matches_idle_blob() {
        // Idle and the canonical (un-rotated) frame are rendered from the
        // same source by build.rs ... they must be byte-identical so that
        // entering and leaving Syncing doesn't visibly twitch.
        assert_eq!(ROT_FRAMES[0], IDLE_RGBA);
    }

    #[test]
    fn offline_blob_differs_from_idle() {
        // Sanity: the offline overlay must visibly differ from idle.
        assert_ne!(IDLE_RGBA, OFFLINE_RGBA);
    }

    #[test]
    fn syncing_to_idle_is_detected_as_exit() {
        let prev = TrayState::Syncing {
            current: 1,
            total: 5,
        };
        let next = TrayState::Idle;
        assert!(is_syncing_exit(&prev, &next));
    }

    #[test]
    fn syncing_to_syncing_is_not_an_exit() {
        let prev = TrayState::Syncing {
            current: 1,
            total: 5,
        };
        let next = TrayState::Syncing {
            current: 2,
            total: 5,
        };
        assert!(!is_syncing_exit(&prev, &next));
    }

    #[test]
    fn syncing_to_offline_is_detected_as_exit() {
        let prev = TrayState::Syncing {
            current: 1,
            total: 5,
        };
        let next = TrayState::Offline;
        assert!(is_syncing_exit(&prev, &next));
    }

    #[test]
    fn idle_to_idle_is_not_an_exit() {
        // No syncing involved.
        assert!(!is_syncing_exit(&TrayState::Idle, &TrayState::Idle));
    }

    #[test]
    fn offline_to_idle_is_not_a_syncing_exit() {
        assert!(!is_syncing_exit(&TrayState::Offline, &TrayState::Idle));
    }
}
